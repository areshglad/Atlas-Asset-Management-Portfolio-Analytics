-- RA01 – Average Volatility by Portfolio Type
SELECT
    portfolio_type,
    ROUND(AVG(volatility_pct),2) AS avg_volatility
FROM atlas
GROUP BY portfolio_type
ORDER BY avg_volatility DESC;

-- RA02 – Average Beta by Asset Class
SELECT
    asset_class,
    ROUND(AVG(beta),2) AS avg_beta
FROM atlas
GROUP BY asset_class
ORDER BY avg_beta DESC;

-- RA03 – Risk Distribution by Risk Level
SELECT
    risk_level,
    COUNT(*) AS holdings_count,
    ROUND(SUM(market_value),2) AS total_market_value
FROM atlas
GROUP BY risk_level
ORDER BY total_market_value DESC;

-- RA04 – Highest Risk Portfolios
SELECT
    portfolio_id,
    portfolio_type,
    ROUND(volatility_pct,2) AS volatility_pct
FROM atlas
ORDER BY volatility_pct DESC
LIMIT 10;

-- RA05 – Concentration Risk Analysis
SELECT
    portfolio_id,
    portfolio_type,
    ROUND(concentration_risk_score,2) AS concentration_risk_score
FROM atlas
ORDER BY concentration_risk_score DESC
LIMIT 10;

-- RA06 – Sharpe Ratio by Risk Level
SELECT
    risk_level,
    ROUND(AVG(sharpe_ratio),2) AS avg_sharpe_ratio
FROM atlas
GROUP BY risk_level
ORDER BY avg_sharpe_ratio DESC;

-- RA07 – Alpha vs Risk Profile
SELECT
    risk_level,
    ROUND(AVG(alpha),2) AS avg_alpha,
    ROUND(AVG(volatility_pct),2) AS avg_volatility
FROM atlas
GROUP BY risk_level
ORDER BY avg_alpha DESC;

