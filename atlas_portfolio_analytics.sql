/*Executive Analytics Questions */
-- EA-01: What is the total Assets Under Management (AUM) managed by Atlas Asset Management?
select sum(market_value) as total_aum
from atlas;

-- EA-02: How is AUM distributed across portfolio types?
select portfolio_type,sum(market_value) as total_aum
from atlas
group by portfolio_type
order by total_aum desc;

-- EA-03: Which investor segments contribute the highest market value?
SELECT investor_segment, SUM(market_value) AS total_market_value
FROM atlas
GROUP BY investor_segment
ORDER BY total_market_value DESC;

-- EA-04: What are the top 10 portfolios by market value?
select portfolio_id, sum(market_value) as portfolio_value
from atlas
group by portfolio_id
order by portfolio_value desc
limit 10;

-- EA-05: Which asset classes contribute the largest share of portfolio value?
select asset_class,sum(market_value) as total_market_value
from atlas
group by asset_class
order by total_market_value desc;

-- EA-06: Which sectors represent the largest investment exposure?
select sector,sum(market_value) as total_market_value
from atlas
group by sector
order by total_market_value desc;

-- EA-07: How much management fee revenue is generated by each portfolio type?
select portfolio_type, sum(management_fee_revenue) as total_fee_revenue
from atlas
group by portfolio_type
order by total_fee_revenue desc;

-- EA-08: What percentage of portfolios currently require rebalancing?
select rebalancing_needed,count(*) as portfolio_count,
round(count(*)*100/sum(count(*)) over(),2) as percentage_share 
from atlas
group by rebalancing_needed;

/*PORTFOLIO PERFORMANCE ANALYTICS */

-- PP01 — Average Annual Return by Portfolio Type

select portfolio_type,round(avg(monthly_return_pct),2) as avg_annual_return_pct
from atlas
group by portfolio_type
order by avg_annual_return_pct desc;

-- PP02 — Average Monthly Return by Asset Class
select asset_class,round(avg(monthly_return_pct),2) as avg_monthly_return_pct
from atlas
group by asset_class
order by avg_monthly_return_pct desc;

-- PP03 — Benchmark vs Portfolio Return
SELECT
    portfolio_type,
    ROUND(AVG(annual_return_pct), 2) AS avg_portfolio_return,
    ROUND(AVG(benchmark_return_pct), 2) AS avg_benchmark_return,
    ROUND(AVG(active_return_pct), 2) AS avg_active_return
FROM atlas
GROUP BY portfolio_type
ORDER BY avg_active_return DESC;

-- PP04 — Top 10 Portfolios by Annual Return
SELECT
    portfolio_id,
    portfolio_type,
    investor_segment,
    ROUND(annual_return_pct, 2) AS annual_return_pct,
    ROUND(benchmark_return_pct, 2) AS benchmark_return_pct,
    ROUND(active_return_pct, 2) AS active_return_pct
FROM atlas
ORDER BY annual_return_pct DESC
LIMIT 10;

-- PP05 — Top Alpha Generating Portfolios
SELECT
    portfolio_id,
    portfolio_type,
    asset_class,
    ROUND(alpha, 2) AS alpha,
    ROUND(annual_return_pct, 2) AS annual_return_pct
FROM atlas
ORDER BY alpha DESC
LIMIT 10;

-- PP06 — Best Risk-Adjusted Portfolios by Sharpe Ratio
SELECT
    portfolio_id,
    portfolio_type,
    asset_class,
    ROUND(sharpe_ratio, 2) AS sharpe_ratio,
    ROUND(volatility_pct, 2) AS volatility_pct,
    ROUND(annual_return_pct, 2) AS annual_return_pct
FROM atlas
ORDER BY sharpe_ratio DESC
LIMIT 10;

-- PP07 — Dividend Income by Asset Class
SELECT
    asset_class,
    ROUND(SUM(dividend_income), 2) AS total_dividend_income,
    ROUND(AVG(dividend_income), 2) AS avg_dividend_income
FROM atlas
GROUP BY asset_class
ORDER BY total_dividend_income DESC;

/* =====================================================
